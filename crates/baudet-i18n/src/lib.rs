//! Localized interface text. Model-facing instructions stay in English.

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Language {
    #[default]
    En,
    Nl,
    Fr,
    De,
}

impl Language {
    pub const ALL: [Language; 4] = [Language::En, Language::Nl, Language::Fr, Language::De];

    pub fn word(self) -> &'static str {
        match self {
            Language::En => "en",
            Language::Nl => "nl",
            Language::Fr => "fr",
            Language::De => "de",
        }
    }

    pub fn native_name(self) -> &'static str {
        match self {
            Language::En => "English",
            Language::Nl => "Nederlands",
            Language::Fr => "Francais",
            Language::De => "Deutsch",
        }
    }

    pub(crate) fn as_code_byte(self) -> u8 {
        match self {
            Language::En => 0,
            Language::Nl => 1,
            Language::Fr => 2,
            Language::De => 3,
        }
    }

    pub(crate) fn from_code_byte(byte: u8) -> Language {
        match byte {
            1 => Language::Nl,
            2 => Language::Fr,
            3 => Language::De,
            _ => Language::En,
        }
    }

    pub fn parse(stored: &str) -> Language {
        match stored.trim().to_ascii_lowercase().as_str() {
            "nl" => Language::Nl,
            "fr" => Language::Fr,
            "de" => Language::De,
            _ => Language::En,
        }
    }
}

